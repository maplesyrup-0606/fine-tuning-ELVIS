#!/usr/bin/env python3
"""
Slide-ready PNG cards: the 3+3 Stage 1 example images and the rule a model wrote from them.

One card per (principle, model) for one sampled pattern per principle (same pattern for
every model). Reads saved standard-mode results (the rule is the result JSON's
logic_rules); no model runs. --with-truth adds the ground-truth rubric under the rule.

Usage:
  python scripts/rule_cards.py                                   # all principles, all models
  python scripts/rule_cards.py --models base all-both --with-truth --seed 3
  python scripts/rule_cards.py --principles closure --pattern 120_
Writes results/rule_cards/<principle>_<pattern id>_<model>.png
"""

import argparse
import json
import os
import random
import sys
import textwrap
from pathlib import Path

from PIL import Image, ImageDraw

from review_samples import ALL_PRINCIPLES, MODEL_ORDER, find_runs, load_results
from show_episode import font

TILE, PAD, GAP = 224, 16, 28          # GAP separates the positive and negative groups
POS, NEG, INK, INK2, BG = "#1a7f4b", "#c0392b", "#0b0b0b", "#52514e", "white"
WRAP = 105


def card(principle, model, examples, rule, truth=None):
    """examples: [(path, is_positive)] x6 -> PIL image."""
    f_title, f_head, f_text = font(30), font(22), font(22)
    width = 2 * PAD + 6 * TILE + 4 * PAD + GAP
    blocks = [("Rule generated by the model:", rule, INK)]
    if truth:
        blocks.append(("Ground truth:", truth, INK2))
    lines = []
    for head, body, color in blocks:
        lines.append((head, f_head, color, True))
        for para in body.strip().split("\n"):
            lines += [(l, f_text, color, False) for l in (textwrap.wrap(para, WRAP) or [""])]
        lines.append(("", f_text, color, False))
    height = PAD + 44 + 34 + TILE + PAD + 12 + len(lines) * 30 + PAD
    img = Image.new("RGB", (width, height), BG)
    d = ImageDraw.Draw(img)

    d.text((PAD, PAD), f"{principle}  ·  {model}", fill=INK, font=f_title)
    y_head, y_img = PAD + 44, PAD + 44 + 34
    x = PAD
    for k, (path, is_pos) in enumerate(examples):
        if k == 3:
            x += GAP
        if k in (0, 3):
            d.text((x, y_head), "Positive examples" if is_pos else "Negative examples",
                   fill=POS if is_pos else NEG, font=f_head)
        img.paste(Image.open(path).convert("RGB").resize((TILE, TILE)), (x, y_img))
        d.rectangle([x - 2, y_img - 2, x + TILE + 1, y_img + TILE + 1], outline=POS if is_pos else NEG, width=4)
        x += TILE + PAD
    y = y_img + TILE + PAD + 12
    for text, f, color, bold in lines:
        d.text((PAD, y), text, fill=color, font=f, stroke_width=1 if bold else 0, stroke_fill=color)
        y += 30
    return img


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--standard-root", default="results/eval_v3_on_test_v3")
    parser.add_argument("--examples-split", default="train_v3")
    parser.add_argument("--principles", nargs="+", default=ALL_PRINCIPLES)
    parser.add_argument("--models", nargs="+", default=None, help="default: every model found")
    parser.add_argument("--pattern", default=None, help="substring of the pattern name (default: random)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--with-truth", action="store_true", help="add the ground-truth rubric")
    parser.add_argument("--out", default="results/rule_cards")
    args = parser.parse_args()

    data = os.environ.get("ELVIS_DATA")
    if not data:
        sys.exit("ERROR: env var ELVIS_DATA is not set")
    data = Path(data)

    runs = find_runs(args.standard_root)
    models = [m for m in sorted(runs, key=lambda m: MODEL_ORDER.index(m) if m in MODEL_ORDER else 99)
              if args.models is None or m in args.models]
    if not models:
        sys.exit(f"ERROR: no matching models under {args.standard_root} (found: {sorted(runs)})")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    for principle in args.principles:
        results = {m: load_results(runs[m], principle) for m in models}
        patterns = sorted(set.intersection(*(set(r) for r in results.values())))
        if args.pattern:
            patterns = [p for p in patterns if args.pattern in p]
        if not patterns:
            print(f"[skip] {principle}: no pattern found in every model's results")
            continue
        pattern = random.Random(f"{args.seed}-{principle}").choice(patterns)
        pick = lambda side: sorted((data / principle / args.examples_split / pattern / side).glob("*.png"))[:3]
        examples = [(p, True) for p in pick("positive")] + [(p, False) for p in pick("negative")]
        truth = None
        if args.with_truth:
            truth = json.load(open(f"data/{principle}/rubrics.json"))["rubrics"].get(pattern)
        print(f"\n{principle}: {pattern}")
        for m in models:
            rule = results[m][pattern].get("logic_rules") or "(no rule saved)"
            path = out / f"{principle}_{pattern[:3]}_{m}.png"
            card(principle, m, examples, rule, truth).save(path)
            print(f"  {m:16s} -> {path}")


if __name__ == "__main__":
    main()
